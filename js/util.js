export function numOptions(ans, spread = [1, 2, 3, -1, -2, 5, 10, -10], n = 4) {
  const set = new Set([ans]);
  const cand = shuffle(spread.map((d) => ans + d));
  for (const c of cand) { if (set.size >= n) break; if (Number.isFinite(c)) set.add(round(c, 2)); }
  let k = 4; while (set.size < n) set.add(ans + k++);
  return shuffle([...set]);
}

